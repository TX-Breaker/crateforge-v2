import { fr, de } from './i18nPagesFrDe';

export const pages = { it, en, fr, de } as unknown as Record<
  Locale,
  Record<string, Record<string, string>>
>;

export type { PageDict };

/**
 * Testo di pagina con sostituzione dei segnaposto {x}. Se la chiave manca
 * nella lingua attiva si ricade sull'italiano, e in ultima istanza sulla
 * chiave stessa: mai una stringa vuota, mai un crash.
 */
export function pageText(locale: Locale, ns: string, key: string, params?: Params): string {
  const raw = pages[locale]?.[ns]?.[key] ?? pages.it?.[ns]?.[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}
