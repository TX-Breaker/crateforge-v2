export const STRINGS: Record<Locale, Dict> = { it, en, fr, de };

export type StrParams = Record<string, string | number>;

/** Testo per chiave, con `{nome}` sostituiti dai parametri. */
export function tr(locale: Locale, key: StrKey, params?: StrParams): string {
  const raw = STRINGS[locale]?.[key] ?? it[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

/** `const t = useT(); t('nav.library')` — legato alla lingua corrente. */
export function useT(): (key: StrKey, params?: StrParams) => string {
  const { locale } = useAppState();
  /* Stabile per lingua: può stare fra le dipendenze di un effetto senza
     rilanciarlo a ogni render. */
  return useCallback((key: StrKey, params?: StrParams) => tr(locale, key, params), [locale]);
}
